<?php

namespace App\Support\Theme;

/**
 * Turns ThemeTokens into CSS custom properties that Flux and Tailwind already read.
 *
 * Tailwind v4 compiles every utility to a variable (`.rounded-lg` is
 * `border-radius: var(--radius-lg)`, `.p-4` is `calc(var(--spacing) * 4)`,
 * `.bg-red-500` is `var(--color-red-500)`), so re-declaring those variables
 * re-themes the whole app at runtime without rebuilding the stylesheet.
 *
 * Every colour comes straight from the theme's explicit slots; the only
 * derivation left is status seeds growing into full ramps (Flux consumes
 * palettes, not single colours) and, under the auto dark-mode policy, the
 * dark scheme synthesis in DarkScheme.
 */
final class ThemeCompiler
{
    /**
     * Which Tailwind palettes each status colour drives. Flux callouts, badges and
     * toasts use both members of every pair.
     */
    public const STATUS_PALETTES = [
        'info' => ['blue', 'sky'],
        'success' => ['green', 'emerald'],
        'warning' => ['amber', 'yellow'],
        'danger' => ['red', 'rose'],
    ];

    private const FALLBACKS = [
        'sans' => "ui-sans-serif, system-ui, sans-serif, 'Apple Color Emoji', 'Segoe UI Emoji', 'Segoe UI Symbol', 'Noto Color Emoji'",
        'serif' => "ui-serif, Georgia, Cambria, 'Times New Roman', Times, serif",
    ];

    /**
     * CSS for the page: `:root` / `.dark` blocks injected after the Vite stylesheet,
     * or the same tokens scoped to a container for the generator's live preview.
     */
    public function runtime(ThemeTokens $tokens, string $scope = ':root'): string
    {
        ['light' => $light, 'dark' => $dark] = $this->variables($tokens);

        $isRoot = $scope === ':root';

        if (! $isRoot) {
            // Inherited font-family is resolved on <html>, so a scoped preview has to
            // re-apply it for the new --font-sans to show up.
            $light['font-family'] = 'var(--font-sans)';
        }

        $darkScope = $isRoot ? '.dark' : ":is(.dark {$scope}, {$scope}.dark)";

        return $scope.'{'.$this->declarations($light).'}'.$darkScope.'{'.$this->declarations($dark).'}';
    }

    /**
     * A Tailwind v4 snippet for another project's app.css, placed after the Flux import.
     */
    public function export(ThemeTokens $tokens, string $name = 'Custom theme'): string
    {
        ['light' => $light, 'dark' => $dark] = $this->variables($tokens);
        $font = $tokens->fontDefinition();

        $header = "/*\n * Theme: {$name}\n * Generated by design-lab's theme generator. Paste after\n * `@import '../../vendor/livewire/flux/dist/flux.css';` in resources/css/app.css.\n";

        if ($font['bunny'] !== null) {
            $header .= " *\n * Font: add `bunny('{$font['family']}', { weights: [400, 500, 600] })` to the\n * `fonts` option in vite.config.js, or load {$tokens->fontUrl()}\n";
        }

        $header .= " */\n";

        $indent = fn (array $vars, string $pad): string => implode("\n", array_map(
            fn (string $key, string $value): string => "{$pad}{$key}: {$value};",
            array_keys($vars),
            $vars,
        ));

        return $header
            ."\n@theme {\n".$indent($light, '    ')."\n}\n"
            ."\n@layer theme {\n    .dark {\n".$indent($dark, '        ')."\n    }\n}\n"
            ."\n[data-flux-checkbox-indicator] {\n    border-radius: var(--radius-selector, 0.3rem);\n}\n";
    }

    /**
     * The theme's ramps as hex, for swatches.
     *
     * @return array<string, array<int|string, string>>
     */
    public function ramps(ThemeTokens $tokens): array
    {
        $ramps = [
            'accent' => Palette::fromSeed(Color::fromHex($tokens->light->accent)),
            'base' => $tokens->light->zinc,
        ];

        foreach ($tokens->light->status as $status => $seed) {
            if ($seed !== null) {
                $ramps[$status] = Palette::fromSeed(Color::fromHex($seed));
            }
        }

        return array_map(
            fn (array $ramp): array => array_map(fn (mixed $color): string => $color instanceof Color ? $color->toHex() : $color, $ramp),
            $ramps,
        );
    }

    /**
     * @return array{light: array<string, string>, dark: array<string, string>}
     */
    public function variables(ThemeTokens $tokens): array
    {
        $light = $this->schemeVariables($tokens->light);
        $dark = $this->schemeVariables($tokens->darkScheme());

        $light += [
            '--radius-selector' => $this->rem($tokens->radiusSelector),
            '--radius-xs' => $this->rem($tokens->radiusSelector / 2),
            '--radius-sm' => $this->rem($tokens->radiusSelector),
            '--radius-md' => $this->rem($tokens->radiusField * 0.75),
            '--radius-lg' => $this->rem($tokens->radiusField),
            '--radius-xl' => $this->rem($tokens->radiusBox),
            '--radius-2xl' => $this->rem($tokens->radiusBox * 4 / 3),
            '--radius-3xl' => $this->rem($tokens->radiusBox * 2),
            '--spacing' => $this->rem($tokens->spacing),
            '--font-sans' => $this->fontStack($tokens),
        ];

        return ['light' => $light, 'dark' => $dark];
    }

    /**
     * @return array<string, string>
     */
    private function schemeVariables(ThemeScheme $scheme): array
    {
        $vars = [
            '--color-accent' => $scheme->accent,
            '--color-accent-content' => $scheme->accentContent,
            '--color-accent-foreground' => $scheme->accentForeground,
        ];

        foreach ($scheme->zinc as $step => $hex) {
            $vars["--color-zinc-{$step}"] = $hex;
        }

        foreach ($scheme->status as $status => $seed) {
            if ($seed === null) {
                continue;
            }

            foreach (Palette::fromSeed(Color::fromHex($seed)) as $step => $color) {
                foreach (self::STATUS_PALETTES[$status] as $palette) {
                    $vars["--color-{$palette}-{$step}"] = $color->toHex();
                }
            }
        }

        return $vars;
    }

    private function fontStack(ThemeTokens $tokens): string
    {
        $font = $tokens->fontDefinition();

        return "'{$font['family']}', ".self::FALLBACKS[$font['fallback']];
    }

    private function rem(float $value): string
    {
        if ($value <= 0) {
            return '0';
        }

        return rtrim(rtrim(number_format($value, 4, '.', ''), '0'), '.').'rem';
    }

    /**
     * @param  array<string, string>  $vars
     */
    private function declarations(array $vars): string
    {
        return implode(';', array_map(
            fn (string $key, string $value): string => "{$key}:{$value}",
            array_keys($vars),
            $vars,
        ));
    }
}
